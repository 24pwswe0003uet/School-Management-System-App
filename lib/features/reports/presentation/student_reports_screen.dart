import 'package:flutter/material.dart';
import '../domain/entities/report_category.dart';
import '../domain/repositories/report_repository.dart';
import 'unified_report_category_screen.dart';

/// Screen showing Student category reports (delegates to UnifiedReportCategoryScreen).
class StudentReportsScreen extends StatelessWidget {
  const StudentReportsScreen({
    super.key,
    required this.reportRepository,
  });

  final ReportRepository reportRepository;

  @override
  Widget build(BuildContext context) {
    return UnifiedReportCategoryScreen(
      reportRepository: reportRepository,
      category: ReportCategory.student,
      categoryTitle: 'Student Reports',
    );
  }
}
